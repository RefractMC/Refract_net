import { mkdir, writeFile } from 'node:fs/promises';
const username=process.argv[2];
if(!username || !/^[a-zA-Z0-9_]{3,16}$/.test(username))throw new Error('Pass a Minecraft Java username.');
const json=async url=>{const response=await fetch(url,{signal:AbortSignal.timeout(15000)});if(!response.ok)throw new Error(`Profile request failed: ${response.status}`);return response.json();};
const profile=await json(`https://api.mojang.com/users/profiles/minecraft/${username}`);
if(!/^[a-f0-9]{32}$/i.test(profile.id))throw new Error('Invalid profile identifier.');
const session=await json(`https://sessionserver.mojang.com/session/minecraft/profile/${profile.id}`);
const property=session.properties?.find(item=>item.name==='textures');
if(!property)throw new Error('The profile has no public skin texture.');
const textures=JSON.parse(Buffer.from(property.value,'base64').toString('utf8')).textures;
const skin=textures?.SKIN;
if(!skin)throw new Error('The profile has no custom skin.');
const url=new URL(skin.url);
if(url.hostname!=='textures.minecraft.net'||!url.pathname.startsWith('/texture/'))throw new Error('Unexpected skin texture host.');
url.protocol='https:';
const response=await fetch(url,{signal:AbortSignal.timeout(15000)});
if(!response.ok)throw new Error(`Skin download failed: ${response.status}`);
const bytes=Buffer.from(await response.arrayBuffer());
if(bytes.length>2*1024*1024||bytes.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw new Error('Invalid skin image.');
await mkdir('public/images/skins',{recursive:true});
const slug=profile.name.toLowerCase();
await writeFile(`public/images/skins/${slug}.png`,bytes);
await writeFile(`public/images/skins/${slug}.json`,JSON.stringify({username:profile.name,uuid:profile.id,model:skin.metadata?.model==='slim'?'slim':'default',source:url.href},null,2)+'\n');
console.log(`Saved ${profile.name}'s ${skin.metadata?.model==='slim'?'slim':'classic'} skin (${bytes.length} bytes).`);
